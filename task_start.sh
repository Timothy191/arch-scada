#!/usr/bin/env bash
# task_start.sh - deliver specialist pre-context / /swarm briefs.
#
# Usage:
#   bash task_start.sh <Specialist> [--json] [--swarm-brief]
#   bash task_start.sh --list [--json]
#
# Specialists (specialists_registry.yaml v2.0): Desktop Web ThreeD OpenUSD Testing Documentation Security
# (aliases: 3D, USD, Docs, Sec; case-insensitive)
#
# Modes:
#   (default)       live pre-context for the specialist (git, tracks, assets, USD, MCP as per its facets)
#   --swarm-brief   full ready-to-paste /swarm worker brief (memories, boundaries, gates)
#   --json          structured JSON for either mode
# All content is generated by deploy/scripts/swarm_orchestrator.py.
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$PROJECT_ROOT"

ORCHESTRATOR="deploy/scripts/swarm_orchestrator.py"
SPECIALIST=""
WANT_JSON=0
WANT_BRIEF=0
WANT_LIST=0

usage() { sed -n '2,15p' "${BASH_SOURCE[0]}"; }

for arg in "$@"; do
  case "$arg" in
    --json) WANT_JSON=1 ;;
    --swarm-brief) WANT_BRIEF=1 ;;
    --list) WANT_LIST=1 ;;
    -h|--help) usage; exit 0 ;;
    -*) echo "Unknown option: $arg" >&2; usage >&2; exit 2 ;;
    *)
      if [[ -n "$SPECIALIST" ]]; then
        echo "Only one specialist may be given (got '$SPECIALIST' and '$arg')" >&2
        exit 2
      fi
      SPECIALIST="$arg"
      ;;
  esac
done

if [[ ! -f "$ORCHESTRATOR" ]]; then
  echo "Missing $ORCHESTRATOR" >&2
  exit 1
fi

json_flag=()
[[ "$WANT_JSON" -eq 1 ]] && json_flag=(--json)

if [[ "$WANT_LIST" -eq 1 ]]; then
  exec python3 "$ORCHESTRATOR" --list "${json_flag[@]}"
fi

if [[ -z "$SPECIALIST" ]]; then
  usage >&2
  echo >&2
  echo "Available specialists:" >&2
  python3 "$ORCHESTRATOR" --list >&2
  exit 1
fi

context_flag=(--context-only)
[[ "$WANT_BRIEF" -eq 1 ]] && context_flag=()

exec python3 "$ORCHESTRATOR" --brief "$SPECIALIST" "${context_flag[@]}" "${json_flag[@]}"
